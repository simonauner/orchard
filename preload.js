const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('agents', {
  copy: (data) => ipcRenderer.invoke('clipboard:write', data),
  workspaces: () => ipcRenderer.invoke('workspaces:list'),
  addWorkspace: () => ipcRenderer.invoke('workspaces:add'),
  setHidden: (ws, hide) => ipcRenderer.invoke('workspaces:setHidden', ws, hide),
  removeWorkspace: (ws) => ipcRenderer.invoke('workspaces:remove', ws),
  defaults: (workspace) => ipcRenderer.invoke('claude:defaults', workspace),
  settings: () => ipcRenderer.invoke('settings:get'),
  status: () => ipcRenderer.invoke('settings:status'),
  browseClaude: () => ipcRenderer.invoke('settings:browseClaude'),
  setClaudePath: (file) => ipcRenderer.invoke('settings:setClaudePath', file),
  list: () => ipcRenderer.invoke('agent:list'),
  history: (id) => ipcRenderer.invoke('agent:history', id),
  create: (opts) => ipcRenderer.invoke('agent:create', opts),
  remove: (id) => ipcRenderer.invoke('agent:remove', id),
  send: (id, text) => ipcRenderer.invoke('agent:send', id, text),
  stop: (id) => ipcRenderer.invoke('agent:stop', id),
  run: (id, name) => ipcRenderer.invoke('agent:run', id, name),
  runStop: (id) => ipcRenderer.invoke('agent:runStop', id),
  git: (id) => ipcRenderer.invoke('agent:git', id),
  merge: (id, number) => ipcRenderer.invoke('agent:merge', id, number),
  termOpen: (id, cols, rows) => ipcRenderer.invoke('term:open', id, cols, rows),
  termInput: (id, data) => ipcRenderer.send('term:input', id, data),
  termResize: (id, cols, rows) => ipcRenderer.send('term:resize', id, cols, rows),
  onTermData: (cb) => ipcRenderer.on('term:data', (_e, id, data) => cb(id, data)),
  onTermExit: (cb) => ipcRenderer.on('term:exit', (_e, id) => cb(id)),
  onScript: (cb) => ipcRenderer.on('agent:script', (_e, id, kind, line) => cb(id, kind, line)),
  onScriptState: (cb) => ipcRenderer.on('agent:scriptState', (_e, id, kind, running) => cb(id, kind, running)),
  onEvent: (cb) => ipcRenderer.on('agent:event', (_e, id, evt) => cb(id, evt)),
  onInfo: (cb) => ipcRenderer.on('agent:info', (_e, info) => cb(info)),
  onStatus: (cb) => ipcRenderer.on('agent:status', (_e, id, s) => cb(id, s)),
});
